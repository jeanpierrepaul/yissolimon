/** Activités compatibles avec l'âge, la durée et le matériel disponible. */
export function activitesPossibles(age: Age, minutesMax: number, dispo: Materiel[], objectif: Objectif | '') {
  return ACTIVITES.filter((a) => a.ages.includes(age) && a.minutes <= minutesMax
    && a.materiel.every((m) => dispo.includes(m)) && (!objectif || a.objectif === objectif));
}
